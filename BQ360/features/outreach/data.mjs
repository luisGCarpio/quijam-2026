/**
 * Deep clone helper safe in both Node 24 and browser environments without React/DOM.
 * @template T
 * @param {T} value
 * @returns {T}
 */
function deepClone(value) {
  return JSON.parse(JSON.stringify(value));
}

/**
 * Returns a fresh deterministic seed snapshot for the given Barranquilla scenario.
 * @param {'metro-exit-v1' | 'metro-entry-v1'} [scenarioId='metro-exit-v1']
 */
export function createScenarioSeed(scenarioId = 'metro-exit-v1') {
  const key = scenarioId === 'metro-entry-v1' ? 'metro-entry-v1' : 'metro-exit-v1';
  const cfg = SCENARIO_CONFIGS[key];
  return {
    ...deepClone(cfg),
    jobs: deepClone(ILLUSTRATIVE_JOBS),
    issuedAt: INITIAL_TIMESTAMP,
  };
}
