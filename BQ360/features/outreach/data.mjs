const BASE_UTC_MS = Date.UTC(2026, 10, 26, 20, 0, 0); // 2026-11-26T15:00:00-05:00

/**
 * Deterministic ISO-8601 timestamp formatter locked to Colombia time (-05:00).
 * Advances 15 minutes per simulation tick without using Date.now().
 * @param {number} tick
 * @param {number} [extraMinutes=0]
 * @returns {string}
 */
export function formatTickTimestamp(tick, extraMinutes = 0) {
  const safeTick = Number.isFinite(tick) ? Math.max(0, Math.floor(tick)) : 0;
  const totalMinutes = safeTick * 15 + extraMinutes;
  const localWall = new Date(BASE_UTC_MS - 5 * 3600_000 + totalMinutes * 60_000);
  const year = localWall.getUTCFullYear();
  const month = String(localWall.getUTCMonth() + 1).padStart(2, '0');
  const day = String(localWall.getUTCDate()).padStart(2, '0');
  const hours = String(localWall.getUTCHours()).padStart(2, '0');
  const minutes = String(localWall.getUTCMinutes()).padStart(2, '0');
  const seconds = String(localWall.getUTCSeconds()).padStart(2, '0');
  return `${year}-${month}-${day}T${hours}:${minutes}:${seconds}-05:00`;
}

